def query_benefits(
    category: Optional[str] = None,
    benefit_id: Optional[str] = None,
) -> str:
    """查询员工福利项目(B001-B018)。支持类别过滤或 ID 直接查询。

    Args:
        category: 福利类别(社保/补充医疗/体检/团建/设备/培训/餐饮/通讯/休假/股票/期权/关怀/弹性)
        benefit_id: 直接查 B001-B018
    """
    items = _BENEFITS
    if benefit_id:
        items = [b for b in items if b["id"].upper() == benefit_id.upper()]
    elif category and category != "全部":
        # 改成严格相等,避免子串误命中
        items = [b for b in items if category == b["category"]]
    return json.dumps({
        "status": "success" if items else "no_data",
        "data": items,
        "message": "未找到符合条件的福利项目。" if not items else "",
    }, ensure_ascii=False)


