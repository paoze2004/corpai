def seed_default_kb() -> int:
    """注入默认企业 FAQ KB(in-memory + Milvus upsert)。

    v3.0 — 106 条。Milvus upsert 走 delete-by-doc_id-then-insert,避免累积。

    Returns:
        注入条数(in-memory 计数)。
    """
    from faq import milvus_store as ms

    count = 0
    docs = [{"id": d["id"], "text": d["text"]} for d in DEFAULT_KB]
    # 1. in-memory 灌入(幂等,_dedup_append)
    for d in docs:
        add_document(text=d["text"], collection=DEFAULT_COLLECTION, doc_id=d["id"])
        count += 1

    # 2. Milvus delete-by-doc_id + insert(去重语义)
    try:
        inserted = ms.upsert(docs)
        logger.info(
            f"已向 Milvus 写入 {inserted}/{len(docs)} 条 FAQ 到 {ms._cfg.faq_collection}"
        )
    except ms.MilvusUnreachable as e:
        logger.warning(
            f"Milvus upsert 失败({e});仅 _DOC_STORE 可用 — query_faq 仍可降级"
        )
    return count


if __name__ == "__main__":
    n = seed_default_kb()
    print(f"已注入 {n} 条 FAQ 文档")
